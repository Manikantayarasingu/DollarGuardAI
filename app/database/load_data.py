"""
DollarGuard AI
Database Data Loader

Loads the synthetic enterprise financial datasets generated by
scripts/generate_data.py into the application's SQLite database.

Tables created:

    vendors
    contracts
    purchase_orders
    goods_receipts
    invoices
    payments
    rebates
    credit_notes
    ground_truth

The loader is designed to be safely re-run.
Existing application tables are replaced with the latest CSV data.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from sqlalchemy import inspect, text

from app.database.connection import engine


# ============================================================
# PATH CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).resolve().parents[2]

DATA_DIR = (
    BASE_DIR
    / "data"
    / "synthetic"
)


# ============================================================
# DATASET CONFIGURATION
# ============================================================

DATASETS = {
    "vendors": "vendors.csv",
    "contracts": "contracts.csv",
    "purchase_orders": "purchase_orders.csv",
    "goods_receipts": "goods_receipts.csv",
    "invoices": "invoices.csv",
    "payments": "payments.csv",
    "rebates": "rebates.csv",
    "credit_notes": "credit_notes.csv",
    "ground_truth": "ground_truth.csv",
}


# ============================================================
# DATABASE UTILITIES
# ============================================================

def get_existing_tables() -> list[str]:
    """
    Return all tables currently present in the database.
    """

    inspector = inspect(engine)

    return inspector.get_table_names()


def clear_existing_tables() -> None:
    """
    Remove previously loaded financial tables.

    This allows the data loader to be safely re-run without
    accumulating duplicate rows.
    """

    tables = [
        table_name
        for table_name in DATASETS
        if table_name in get_existing_tables()
    ]

    if not tables:
        return

    with engine.begin() as connection:

        for table_name in tables:

            connection.execute(
                text(
                    f'DROP TABLE IF EXISTS "{table_name}"'
                )
            )

    print(
        f"Removed {len(tables)} existing financial tables."
    )


# ============================================================
# CSV VALIDATION
# ============================================================

def validate_data_directory() -> None:
    """
    Verify that the synthetic data directory exists.
    """

    if not DATA_DIR.exists():

        raise FileNotFoundError(
            f"Data directory does not exist:\n{DATA_DIR}\n\n"
            "Run the following command first:\n"
            "python scripts\\generate_data.py"
        )


def validate_dataset_files() -> None:
    """
    Verify that all expected CSV files exist.
    """

    missing_files = []

    for filename in DATASETS.values():

        file_path = DATA_DIR / filename

        if not file_path.exists():

            missing_files.append(
                filename
            )

    if missing_files:

        formatted = "\n".join(
            f"  - {filename}"
            for filename in missing_files
        )

        raise FileNotFoundError(
            "The following required datasets are missing:\n"
            f"{formatted}\n\n"
            "Run:\n"
            "python scripts\\generate_data.py"
        )


# ============================================================
# DATA CLEANING
# ============================================================

def clean_dataframe(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Perform basic generic cleaning before loading data.

    More advanced business-specific cleaning will be added
    later in the data pipeline.
    """

    dataframe = dataframe.copy()

    # Remove completely empty rows.
    dataframe = dataframe.dropna(
        how="all"
    )

    # Remove leading/trailing whitespace from column names.
    dataframe.columns = [
        str(column).strip()
        for column in dataframe.columns
    ]

    # Strip whitespace from string columns.
    for column in dataframe.select_dtypes(
        include=["object"]
    ).columns:

        dataframe[column] = (
            dataframe[column]
            .astype(str)
            .str.strip()
        )

    return dataframe


# ============================================================
# LOAD ONE DATASET
# ============================================================

def load_dataset(
    table_name: str,
    filename: str,
) -> int:
    """
    Load one CSV file into one database table.

    Returns the number of rows inserted.
    """

    file_path = DATA_DIR / filename

    dataframe = pd.read_csv(
        file_path
    )

    dataframe = clean_dataframe(
        dataframe
    )

    dataframe.to_sql(
        table_name,
        con=engine,
        if_exists="replace",
        index=False,
    )

    return len(dataframe)


# ============================================================
# CREATE DATABASE INDEXES
# ============================================================

def create_indexes() -> None:
    """
    Create indexes on frequently queried financial columns.

    These indexes will improve performance when the leakage
    detection engine starts joining large transaction tables.
    """

    indexes = [
        (
            "idx_contracts_vendor_id",
            "contracts",
            "vendor_id",
        ),
        (
            "idx_contracts_sku",
            "contracts",
            "sku",
        ),
        (
            "idx_purchase_orders_vendor_id",
            "purchase_orders",
            "vendor_id",
        ),
        (
            "idx_purchase_orders_contract_id",
            "purchase_orders",
            "contract_id",
        ),
        (
            "idx_goods_receipts_po_id",
            "goods_receipts",
            "po_id",
        ),
        (
            "idx_invoices_vendor_id",
            "invoices",
            "vendor_id",
        ),
        (
            "idx_invoices_po_id",
            "invoices",
            "po_id",
        ),
        (
            "idx_invoices_sku",
            "invoices",
            "sku",
        ),
        (
            "idx_payments_invoice_id",
            "payments",
            "invoice_id",
        ),
        (
            "idx_payments_vendor_id",
            "payments",
            "vendor_id",
        ),
        (
            "idx_rebates_vendor_id",
            "rebates",
            "vendor_id",
        ),
        (
            "idx_credit_notes_vendor_id",
            "credit_notes",
            "vendor_id",
        ),
        (
            "idx_ground_truth_invoice_id",
            "ground_truth",
            "invoice_id",
        ),
        (
            "idx_ground_truth_vendor_id",
            "ground_truth",
            "vendor_id",
        ),
    ]

    with engine.begin() as connection:

        for (
            index_name,
            table_name,
            column_name,
        ) in indexes:

            connection.execute(
                text(
                    f'''
                    CREATE INDEX IF NOT EXISTS
                    "{index_name}"
                    ON "{table_name}"
                    ("{column_name}")
                    '''
                )
            )

    print(
        f"Created/verified {len(indexes)} database indexes."
    )


# ============================================================
# DATABASE SUMMARY
# ============================================================

def get_database_summary() -> dict[str, int]:
    """
    Return row counts for all loaded financial tables.
    """

    summary = {}

    with engine.connect() as connection:

        for table_name in DATASETS:

            result = connection.execute(
                text(
                    f'''
                    SELECT COUNT(*)
                    FROM "{table_name}"
                    '''
                )
            )

            summary[table_name] = int(
                result.scalar() or 0
            )

    return summary


